#!/bin/bash
cd "$(dirname "$0")" || exit 1

echo "Сделайте так, чтобы этот скрипт не мог запустить файл file.txt"
echo "При помощи правильной настройки прав"
echo "-----------------------------------------------------------------"

if [[ -z "$(./file.txt 2> /dev/null )" ]]
then
	echo "Имеешь право(а)!"
else
	echo "Что-то не так"
	chgrp minimal file.txt 2> /dev/null
	chmod 777 file.txt
fi
echo "-----------------------------------------------------------------"
