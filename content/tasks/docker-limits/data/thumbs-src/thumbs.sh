#!/bin/sh
# Сервис превью: держит в памяти всё больше фотографий — до 128 МБ данных, потом ждёт новых.
echo "thumbs: готовлю превью фотографий меню"
x=0123456789abcdef
n=0
while [ ${#x} -lt 134217728 ]; do
    x="$x$x"
    n=$((n + 1))
    echo "обработано фото: $n, в памяти $(( ${#x} / 1048576 )) МБ"
    sleep 1
done
echo "все фото в памяти, жду новых"
while sleep 3600; do :; done
