#!/bin/sh
# Собрать сайт с историей в 46 коммитов: новости, релиз v1.0 с ценами, backup.sh, который
# трижды правили, а потом удалили при «уборке», и цены, которые после v1.0 испортили.
# Даты и автор зафиксированы — хеши одинаковы на любой машине.
# Запуск: mkrepo.sh <каталог-с-data> <куда>
set -eu
src=$1 dst=$2
mkdir -p "$dst"
cd "$dst"
git init -q -b main
n=0
c() {  # c "сообщение"
    n=$((n + 1))
    d=$(date -u -d "2026-03-01 +$((n * 4)) days 10:00" +%Y-%m-%dT%H:%M:%S+00:00)
    git add -A
    GIT_AUTHOR_NAME="Анна Смирнова" GIT_AUTHOR_EMAIL="anna@pelmen.local" GIT_AUTHOR_DATE="$d" \
    GIT_COMMITTER_NAME="Анна Смирнова" GIT_COMMITTER_EMAIL="anna@pelmen.local" GIT_COMMITTER_DATE="$d" \
        git commit -q -m "$1"
}
put() { cp "$src/site/$1" "$1" && chmod "$2" "$1"; }
mkdir -p posts
post() {  # post N "заголовок"
    printf '# %s\n\n%s\n' "$2" "Новость номер $1. Подробности — у нас в зале и в доставке." > "posts/$(printf %02d "$1").md"
    c "Новость: $2"
}
put README.md 644; put index.html 644; put prices.txt 644; c "Сайт: первая версия"
put backup.sh 755; put deploy-old.sh 755; c "Скрипты: резервная копия и выкладка"
post 1 "Мы открылись"
post 2 "Вареники с вишней"
post 3 "Доставка до полуночи"
sed -i 's/^морс               120$/морс               130/' prices.txt; c "Цены: морс"
git tag v1.0
post 4 "Бизнес-ланч"
post 5 "Пельмени с бараниной — скоро"
sed -i 's|^cp -r ./\* "$dst"/$|cp -r --exclude=.git ./* "$dst"/ 2>/dev/null \|\| cp -r ./* "$dst"/|' backup.sh; c "backup.sh: без .git"
post 6 "Мастер-класс по лепке"
post 7 "Новый зал на Арбате"
cat > backup.sh <<'SH'
#!/bin/sh
# Резервная копия сайта в /var/backups/site — храним 14 последних
set -e
root=/var/backups/site
dst=$root/$(date +%F)
mkdir -p "$dst"
cp -r ./* "$dst"/
ls -1d "$root"/*/ | head -n -14 | xargs -r rm -rf
echo "Копия: $dst"
SH
c "backup.sh: храним 14 копий"
post 8 "Летняя веранда"
post 9 "Окрошка вернулась"
sed -i 's/^пельмени-говядина  390$/пельмени-говядина  3900/; s/^вареники-вишня     320$/вареники-вишня     32/' prices.txt
c "Цены: обновил"
post 10 "Мы в Яндекс Еде"
sed -i 's/храним 14 последних/храним 14 последних (проверено на проде)/' backup.sh; c "backup.sh: комментарий"
post 11 "Отзывы гостей"
post 12 "Вакансия: повар"
git rm -q backup.sh deploy-old.sh; c "Уборка: старые скрипты"
i=13
for t in "Осеннее меню" "Тыквенный суп" "Скидка студентам" "Новый курьер" "День рождения Пельменя" \
         "Подарочные карты" "Конкурс рецептов" "Итоги конкурса" "Зимние часы работы" "Глинтвейн" \
         "Ёлка в зале" "Новогодние сеты" "Предзаказ на 31-е" "Каникулы: работаем" "Спасибо за год" \
         "Пельмени с крабом" "Вареники с творогом" "Мы на ярмарке" "Масленица: блины" "8 марта" \
         "Весеннее меню" "Пасхальные куличи" "Субботник" "Майские праздники"; do
    post $i "$t"; i=$((i + 1))
done
