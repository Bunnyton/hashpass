#!/bin/sh
# Проверка кассы: небольшие заказы считаются по полной цене. Молчит — всё хорошо.
cd "$(dirname "$0")"
fail=0
check() {  # check <ожидаемо> <заказ…>
    want=$1; shift
    got=$(./price.sh "$@")
    [ "$got" = "$want" ] || { echo "FAIL: $* — ждали $want, получили $got"; fail=1; }
}
check 700  пельмени-курица 2
check 1040 пельмени-говядина 2 морс 2
check 290  вареники-картошка 1
exit $fail
